def topic_ids():
    return [t["id"] for t in TOPICS]


def counts():
    """Per-topic counts of flashcards and quiz questions."""
    out = {}
    for t in TOPICS:
        out[t["id"]] = {
            "flashcards": sum(1 for c in FLASHCARDS if c["topic"] == t["id"]),
            "quiz": sum(1 for q in QUIZ if q["topic"] == t["id"]),
        }
    return out


def validate():
    """Raise AssertionError if the content is internally inconsistent."""
    ids = topic_ids()
    seen = set()
    for c in FLASHCARDS:
        assert c["topic"] in ids, "unknown topic %r on %s" % (c["topic"], c["id"])
        assert c["id"] not in seen, "duplicate id %s" % c["id"]
        seen.add(c["id"])
        for field in ("q", "a", "cite"):
            assert c.get(field), "%s is missing %s" % (c["id"], field)
    for q in QUIZ:
        assert q["topic"] in ids, "unknown topic %r on %s" % (q["topic"], q["id"])
        assert q["id"] not in seen, "duplicate id %s" % q["id"]
        seen.add(q["id"])
        assert q["correct"] in q["options"], \
            "%s: correct answer %r not in options" % (q["id"], q["correct"])
        assert len(q["options"]) >= 3, "%s: too few options" % q["id"]
        for field in ("q", "source", "explanation"):
            assert q.get(field), "%s is missing %s" % (q["id"], field)
    return True


if __name__ == "__main__":
    validate()
    print("%d topics, %d flashcards, %d quiz questions"
          % (len(TOPICS), len(FLASHCARDS), len(QUIZ)))
    for tid, c in counts().items():
        print("  %-16s %3d flashcards  %3d questions"
              % (tid, c["flashcards"], c["quiz"]))
